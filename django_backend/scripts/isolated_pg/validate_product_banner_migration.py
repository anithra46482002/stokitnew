"""Isolated-PostgreSQL validation of migration legacydb.0006_product_discount_banner.

SAFETY: runs ONLY against a throw-away database named stokit_iso_* on localhost. It refuses any other host or
database name, never reads .env, and uses synthetic fixtures only. It DROPS and recreates that scratch database.

Usage (from django_backend), with a disposable PostgreSQL server (trust auth) already running:
    set ISO_PG_PORT=55433            (default 55433)
    set ISO_PG_USER=iso              (default iso)
    set ISO_PG_PASSWORD=             (default empty)
    set ISO_DDL=<path to STOKIT_COMPLETE_DDL_CANDIDATE.sql>   (generated by scripts/generate_legacy_pg_ddl.py)
    python scripts/isolated_pg/validate_product_banner_migration.py
The scratch DB is rebuilt as PRODUCTION-SHAPED: the candidate DDL, but zg_discount_banners is replaced with the real
production shape (id, title, image, link, is_active, created_at) holding a sentinel row that must survive untouched.
"""
import hashlib
import json
import os
import sys
from decimal import Decimal
from pathlib import Path
from unittest import mock

import psycopg

HOST = "127.0.0.1"
PORT = os.environ.get("ISO_PG_PORT", "55433")
USER = os.environ.get("ISO_PG_USER", "iso")
PASSWORD = os.environ.get("ISO_PG_PASSWORD", "")
DB = "stokit_iso_mig"
DDL = Path(os.environ.get("ISO_DDL", Path(__file__).resolve().parents[2] / "docs" / "STOKIT_COMPLETE_DDL_CANDIDATE.sql"))
assert DB.startswith("stokit_iso_") and HOST in ("127.0.0.1", "localhost")

RESULTS = []


def check(name, ok, detail=""):
    RESULTS.append((name, bool(ok)))
    print(("PASS  " if ok else "FAIL  ") + name + (f"  [{detail}]" if detail and not ok else ""))


def conn(dbname):
    return psycopg.connect(host=HOST, port=PORT, user=USER, password=PASSWORD, dbname=dbname, autocommit=True)


def sql(c, query, params=None):
    with c.cursor() as cur:
        cur.execute(query, params)
        return cur.fetchall() if cur.description else None


def build_scratch_database():
    with conn("postgres") as admin:
        sql(admin, f"DROP DATABASE IF EXISTS {DB}")
        sql(admin, f"CREATE DATABASE {DB}")
    with conn(DB) as c:
        sql(c, DDL.read_text(encoding="utf-8"))
        # Replace the candidate's product-linked table with the REAL production shape + a sentinel row.
        sql(c, "DROP TABLE zg_discount_banners")
        sql(c, "CREATE TABLE zg_discount_banners (id serial PRIMARY KEY, title varchar(255), image varchar(255), link varchar(255),"
               " is_active boolean DEFAULT true, created_at timestamp DEFAULT CURRENT_TIMESTAMP)")
        sql(c, "INSERT INTO zg_discount_banners (title, image, link) VALUES ('sentinel', 'uploads/sentinel.webp', 'https://example.invalid')")


def fingerprint(c, table):
    rows = sql(c, f"SELECT * FROM {table} ORDER BY 1")
    return hashlib.sha256(json.dumps(rows, default=str).encode()).hexdigest()


def main():
    if not DDL.exists():
        sys.exit(f"DDL candidate not found: {DDL}")
    build_scratch_database()
    os.environ.update({"DJANGO_SECRET_KEY": "isolated-validation-only-0123456789abcdef", "DB_NAME": DB, "DB_USER": USER,
                       "DB_PASSWORD": PASSWORD or "x", "DB_HOST": HOST, "DB_PORT": PORT})
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    import django
    django.setup()
    from django.core.management import call_command
    from django.db import connection

    c = conn(DB)
    before_old = fingerprint(c, "zg_discount_banners")
    before_slider = sql(c, "SELECT count(*) FROM zg_slider")[0][0]

    # 1. migrate: 0001-0003 describe tables the DDL already created (fake), 0004-0006 run for real.
    call_command("migrate", "legacydb", "0003", "--fake", verbosity=0)
    call_command("migrate", "legacydb", verbosity=0)
    applied = [r[0] for r in sql(c, "SELECT name FROM django_migrations WHERE app='legacydb' ORDER BY id")]
    check("migration 0006 applied", "0006_product_discount_banner" in applied)

    # 2. schema
    cols = sql(c, "SELECT column_name, data_type, is_nullable, character_maximum_length FROM information_schema.columns "
                  "WHERE table_name='zg_product_discount_banners' ORDER BY ordinal_position")
    check("columns are id,product_id,image_path,created_at", [r[0] for r in cols] == ["id", "product_id", "image_path", "created_at"], cols)
    types = {r[0]: r for r in cols}
    check("column types", types["id"][1] == "integer" and types["product_id"][1] == "integer" and types["image_path"][1] == "character varying"
          and types["image_path"][3] == 255 and "timestamp" in types["created_at"][1], cols)
    check("product_id/image_path NOT NULL", types["product_id"][2] == "NO" and types["image_path"][2] == "NO")
    pk = sql(c, "SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum=ANY(i.indkey) "
                "WHERE i.indrelid='zg_product_discount_banners'::regclass AND i.indisprimary")
    check("primary key is id", pk == [("id",)], pk)
    idx = sql(c, "SELECT indexname FROM pg_indexes WHERE tablename='zg_product_discount_banners'")
    check("product_id index exists", ("ix_zg_product_discount_banners_product_id",) in idx, idx)
    fk = sql(c, "SELECT confrelid::regclass::text, pg_get_constraintdef(oid) FROM pg_constraint "
                "WHERE conrelid='zg_product_discount_banners'::regclass AND contype='f'")
    check("FK -> zg_product(product_id) ON DELETE CASCADE", len(fk) == 1 and fk[0][0] == "zg_product" and "(product_id)" in fk[0][1]
          and "ON DELETE CASCADE" in fk[0][1], fk)
    check("production zg_discount_banners untouched", fingerprint(c, "zg_discount_banners") == before_old)
    old_cols = [r[0] for r in sql(c, "SELECT column_name FROM information_schema.columns WHERE table_name='zg_discount_banners' ORDER BY ordinal_position")]
    check("production zg_discount_banners columns unchanged", old_cols == ["id", "title", "image", "link", "is_active", "created_at"], old_cols)

    # 3. idempotency: re-running the CREATE SQL must be a no-op
    import importlib
    mig = importlib.import_module("legacydb.migrations.0006_product_discount_banner")
    try:
        sql(c, mig.CREATE_SQL)
        check("CREATE_SQL is idempotent", True)
    except Exception as exc:  # pragma: no cover
        check("CREATE_SQL is idempotent", False, exc)

    # 4. cascade deletion (raw)
    cat = sql(c, "INSERT INTO zg_category (category_name) VALUES ('Iso Cat') RETURNING category_id")[0][0]
    from legacydb.models import Product
    pa = Product.objects.create(product_name="Iso A", code="ISO-A", product_price=Decimal("10"), mrp=Decimal("10"), category_id=cat)
    pb = Product.objects.create(product_name="Iso B", code="ISO-B", product_price=Decimal("20"), mrp=Decimal("20"), category_id=cat)
    sql(c, "INSERT INTO zg_product_discount_banners (product_id, image_path) VALUES (%s,'uploads/a1.webp'),(%s,'uploads/b1.webp')", [pa.product_id, pb.product_id])
    sql(c, "DELETE FROM zg_product WHERE product_id=%s", [pa.product_id])
    left = sql(c, "SELECT product_id FROM zg_product_discount_banners")
    check("cascade deletes only that product's banner rows", left == [(pb.product_id,)], left)
    try:
        sql(c, "INSERT INTO zg_product_discount_banners (product_id, image_path) VALUES (999999,'x')")
        check("FK rejects an unknown product_id", False)
    except psycopg.errors.ForeignKeyViolation:
        check("FK rejects an unknown product_id", True)

    # 5. admin Products API against the real database
    from rest_framework.test import APIRequestFactory, force_authenticate
    from types import SimpleNamespace
    from adminapi import crud
    admin_user = SimpleNamespace(is_authenticated=True, role="ADMIN", pk=1, principal_type="ADMIN")
    factory = APIRequestFactory()

    def call(method, path="/admin-api/products", payload=None):
        req = getattr(factory, method)(path, payload, format="json") if payload is not None else getattr(factory, method)(path)
        force_authenticate(req, user=admin_user)
        return crud.ProductCRUDView.as_view()(req)

    sql(c, "DELETE FROM zg_product_discount_banners")
    r = call("get", "/admin-api/products?search=&page=1&page_size=20")
    prods = {p["id"]: p for p in r.data["results"]}
    check("Products GET -> 200 with zero banners", r.status_code == 200 and prods[pb.product_id]["discount_banners"] == [], getattr(r, "data", ""))
    check("Products GET keeps response keys", {"count", "page", "page_size", "results"} <= set(r.data) and "discount_banners" in prods[pb.product_id])
    sql(c, "INSERT INTO zg_product_discount_banners (product_id, image_path) VALUES (%s,'uploads/b1.webp'),(%s,'uploads/b2.webp')", [pb.product_id, pb.product_id])
    r = call("get", "/admin-api/products?search=Iso&page=1&page_size=20")
    check("Products GET with banners returns ordered paths", r.status_code == 200 and
          {p["id"]: p for p in r.data["results"]}[pb.product_id]["discount_banners"] == ["uploads/b1.webp", "uploads/b2.webp"], r.data)

    r = call("post", payload={"name": "Iso New", "code": "ISO-N", "price": 30, "category_id": cat, "discount_banners": ["uploads/n1.webp", "uploads/n2.webp"]})
    new_id = r.data.get("id") if r.status_code in (200, 201) else None
    stored = sql(c, "SELECT image_path FROM zg_product_discount_banners WHERE product_id=%s ORDER BY id", [new_id]) if new_id else []
    check("Product CREATE saves banner paths", new_id and stored == [("uploads/n1.webp",), ("uploads/n2.webp",)], (r.status_code, getattr(r, "data", ""), stored))
    check("CREATE response keeps discount_banners key", new_id and r.data.get("discount_banners") == ["uploads/n1.webp", "uploads/n2.webp"])

    r = call("patch", payload={"id": new_id, "name": "Iso New 2"})
    kept = sql(c, "SELECT image_path FROM zg_product_discount_banners WHERE product_id=%s ORDER BY id", [new_id])
    check("UPDATE without discount_banners retains existing banners", r.status_code == 200 and len(kept) == 2, (r.status_code, kept))
    r = call("patch", payload={"id": new_id, "discount_banners": ["uploads/n2.webp", "uploads/n3.webp"]})
    now = [x[0] for x in sql(c, "SELECT image_path FROM zg_product_discount_banners WHERE product_id=%s ORDER BY id", [new_id])]
    check("UPDATE removes dropped and adds new banners", r.status_code == 200 and now == ["uploads/n2.webp", "uploads/n3.webp"], (r.status_code, now))
    other = sql(c, "SELECT count(*) FROM zg_product_discount_banners WHERE product_id=%s", [pb.product_id])[0][0]
    check("UPDATE leaves other products' banners alone", other == 2, other)
    r = call("patch", payload={"id": new_id, "discount_banners": []})
    check("UPDATE with empty list removes all banners", r.status_code == 200 and sql(c, "SELECT count(*) FROM zg_product_discount_banners WHERE product_id=%s", [new_id])[0][0] == 0)
    call("patch", payload={"id": new_id, "discount_banners": ["uploads/n9.webp"]})

    # 6. Flutter product-detail endpoint
    from django.test import RequestFactory
    from legacy_api import views_catalog
    user = {"id": 7, "username": "iso-user", "email": "i@example.invalid", "fullname": "I", "phone": "1", "address": "a"}
    sql(c, "INSERT INTO zg_product_images (product_id, image_path, main) VALUES (%s,'uploads/img.webp','1')", [pb.product_id])
    rf = RequestFactory()
    req = rf.post("/api/product-api", data=json.dumps({"product_id": pb.product_id}), content_type="application/json",
                  HTTP_AUTHORIZATION="Bearer " + "a" * 64, HTTP_HOST="localhost")
    with mock.patch("accounts.services.authenticate_token", return_value=(object(), user)):
        resp = views_catalog.product_api(req)
    body = json.loads(resp.content)
    prod = body.get("product", {})
    check("Flutter product-api -> 200 success", resp.status_code == 200 and body.get("status") == "success", body)
    check("Flutter key 'discound_banners' kept, 'discount_banners' absent", "discound_banners" in prod and "discount_banners" not in prod)
    banners = prod.get("discound_banners", [])
    check("Flutter banners are absolute URLs ending in the stored path", len(banners) == 2 and all(b.startswith("http") for b in banners)
          and banners[0].endswith("uploads/b1.webp") and banners[1].endswith("uploads/b2.webp"), banners)

    # 7. delete cleans only that product's banners
    r = call("delete", f"/admin-api/products?id={new_id}")
    check("Product DELETE -> 204", r.status_code == 204, (r.status_code, getattr(r, "data", "")))
    check("DELETE removed that product's banners only",
          sql(c, "SELECT count(*) FROM zg_product_discount_banners WHERE product_id=%s", [new_id])[0][0] == 0
          and sql(c, "SELECT count(*) FROM zg_product_discount_banners WHERE product_id=%s", [pb.product_id])[0][0] == 2)

    # 8. general promotional banners are independent
    sql(c, "INSERT INTO zg_slider (image_path, text_content, styled_text, styled_color, back, text_content2) "
           "VALUES ('uploads/slider1.webp','','','','','')")
    from legacy_api import views_catalog as vc
    breq = rf.post("/api/banner", data="{}", content_type="application/json", HTTP_HOST="localhost")
    bresp = vc.banner(breq)
    check("general banner endpoint (zg_slider) still works", bresp.status_code == 200 and "slider1.webp" in bresp.content.decode(), bresp.content[:200])
    check("production zg_discount_banners still untouched after all operations", fingerprint(c, "zg_discount_banners") == before_old)
    check("zg_slider only gained the test row", sql(c, "SELECT count(*) FROM zg_slider")[0][0] == before_slider + 1)

    # 9. reverse: only the new table is dropped
    connection.close()
    call_command("migrate", "legacydb", "0005", verbosity=0)
    tables = {r[0] for r in sql(c, "SELECT table_name FROM information_schema.tables WHERE table_schema='public'")}
    check("reverse drops zg_product_discount_banners", "zg_product_discount_banners" not in tables)
    check("reverse keeps zg_discount_banners and its data", "zg_discount_banners" in tables and fingerprint(c, "zg_discount_banners") == before_old)
    check("reverse keeps zg_product and other tables", {"zg_product", "zg_product_images", "zg_slider", "zg_variant"} <= tables)
    check("reverse kept product rows", sql(c, "SELECT count(*) FROM zg_product WHERE product_id=%s", [pb.product_id])[0][0] == 1)
    call_command("migrate", "legacydb", verbosity=0)
    check("re-apply after reverse works", sql(c, "SELECT to_regclass('zg_product_discount_banners')")[0][0] is not None)

    c.close()
    failed = [n for n, ok in RESULTS if not ok]
    print(f"\n{len(RESULTS) - len(failed)}/{len(RESULTS)} checks passed")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
